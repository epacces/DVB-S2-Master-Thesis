"""Finite fields GF(2^m) (and a small GF(p) helper for the demos).

Elements of GF(2^m) are integers 0 .. 2^m - 1 whose bits are the coefficients
of a polynomial in alpha (bit i <-> alpha^i).  Addition is XOR; multiplication
uses log/antilog tables built by an LFSR exactly like ``gfField`` in the
thesis' ``gfield.c``.

    >>> F = GF2m(4)                 # x^4 + x + 1
    >>> F.mul(F.alpha_pow(3), F.alpha_pow(14)) == F.alpha_pow(2)
    True
"""
from __future__ import annotations

import numpy as np

from . import poly2

# Default primitive polynomials (full form, including x^m).  m = 14 and 16 are
# the ones DVB-S2 uses for the short- and normal-frame BCH codes.
PRIMITIVE_POLYS = {
    2: 0b111, 3: 0b1011, 4: 0b10011, 5: 0b100101, 6: 0b1000011, 7: 0b10001001,
    8: 0b100011101, 9: 0b1000010001, 10: 0b10000001001, 11: 0b100000000101,
    12: 0b1000001010011, 13: 0b10000000011011, 14: 0x402B, 15: 0b1000000000000011,
    16: 0x1002D,
}


class GF2m:
    """The field GF(2^m) generated by the primitive polynomial ``prim_poly``."""

    def __init__(self, m: int, prim_poly: int | None = None):
        if prim_poly is None:
            prim_poly = PRIMITIVE_POLYS[m]
        if poly2.degree(prim_poly) != m:
            raise ValueError("prim_poly must have degree m")
        self.m = m
        self.prim_poly = prim_poly
        self.q = 1 << m          # number of elements
        self.order = self.q - 1  # order of the multiplicative group

        exp = np.zeros(2 * self.order, dtype=np.int64)
        log = np.full(self.q, -1, dtype=np.int64)  # log(0) = -1, as in gfield.c
        reg = 1
        for i in range(self.order):
            if i and reg == 1:
                raise ValueError("polynomial %s is not primitive" % poly2.to_str(prim_poly))
            exp[i] = reg
            log[reg] = i
            reg <<= 1
            if reg & self.q:
                reg ^= prim_poly
        if reg != 1:
            raise ValueError("polynomial %s is not primitive" % poly2.to_str(prim_poly))
        exp[self.order:] = exp[:self.order]
        self.exp = exp  # exp[i] = alpha^i, doubled so exp[a + b] needs no modulo
        self.log = log

    def __repr__(self):
        return "GF(2^%d) mod %s" % (self.m, poly2.to_str(self.prim_poly))

    # -- scalar / vectorised arithmetic ------------------------------------
    def alpha_pow(self, i):
        return self.exp[np.mod(i, self.order)]

    def add(self, a, b):
        return np.bitwise_xor(a, b)

    def mul(self, a, b):
        a = np.asarray(a)
        b = np.asarray(b)
        out = self.exp[(self.log[a] + self.log[b]) % self.order]
        return np.where((a == 0) | (b == 0), 0, out)[()]

    def inv(self, a):
        a = np.asarray(a)
        if np.any(a == 0):
            raise ZeroDivisionError("0 has no inverse")
        return self.exp[(self.order - self.log[a]) % self.order][()]

    def div(self, a, b):
        return self.mul(a, self.inv(b))

    def pow(self, a, e):
        a = np.asarray(a)
        out = self.exp[(self.log[a] * np.asarray(e)) % self.order]
        return np.where(a == 0, np.where(np.asarray(e) == 0, 1, 0), out)[()]

    def elements(self):
        return np.arange(self.q)

    # -- polynomials with coefficients in GF(2^m), lowest degree first -----
    def poly_eval(self, coeffs, x):
        """Evaluate sum coeffs[i] x^i (Horner) at a scalar or array ``x``."""
        x = np.asarray(x)
        acc = np.zeros_like(x)
        for c in reversed(list(coeffs)):
            acc = self.mul(acc, x) ^ c
        return acc

    def poly_mul(self, a, b):
        out = [0] * (len(a) + len(b) - 1)
        for i, ai in enumerate(a):
            if ai:
                for j, bj in enumerate(b):
                    out[i + j] ^= int(self.mul(ai, bj))
        return out

    # -- structure ---------------------------------------------------------
    def cyclotomic_coset(self, i: int) -> list[int]:
        """Exponents {i, 2i, 4i, ...} mod 2^m - 1: the conjugates of alpha^i."""
        coset, j = [], i % self.order
        while j not in coset:
            coset.append(j)
            j = (2 * j) % self.order
        return coset

    def cyclotomic_cosets(self) -> list[list[int]]:
        seen, cosets = set(), []
        for i in range(self.order):
            if i not in seen:
                c = self.cyclotomic_coset(i)
                seen.update(c)
                cosets.append(c)
        return cosets

    def minimal_polynomial(self, i: int) -> int:
        """Minimal polynomial of alpha^i over GF(2), as a binary int."""
        coeffs = [1]
        for j in self.cyclotomic_coset(i):
            coeffs = self.poly_mul(coeffs, [int(self.alpha_pow(j)), 1])
        assert all(c in (0, 1) for c in coeffs)
        return sum(c << k for k, c in enumerate(coeffs))

    def element_order(self, a: int) -> int:
        if a == 0:
            raise ValueError("0 has no multiplicative order")
        return self.order // np.gcd(self.order, int(self.log[a]))

    def to_poly_str(self, a: int, var: str = "a") -> str:
        """Polynomial representation of an element, e.g. 'a^3 + a + 1'."""
        return poly2.to_str(int(a), var)

    def to_bits(self, a: int) -> str:
        return format(int(a), "0%db" % self.m)


def is_primitive(poly: int) -> bool:
    """True if the binary polynomial generates GF(2^deg) through its powers of x."""
    m = poly2.degree(poly)
    if m < 1 or not poly & 1:
        return False
    return lfsr_cycle_length(poly) == (1 << m) - 1


def lfsr_cycle_length(poly: int) -> int:
    """Period of x^i mod poly starting from 1 (the LFSR state cycle through 1)."""
    m = poly2.degree(poly)
    reg, n = 1, 0
    while True:
        reg <<= 1
        if reg >> m & 1:
            reg ^= poly
        n += 1
        if reg == 1 or n > (1 << m):
            return n


class GFp:
    """Prime field GF(p): integers mod p (used by the introductory demo)."""

    def __init__(self, p: int):
        if p < 2 or any(p % d == 0 for d in range(2, int(p ** 0.5) + 1)):
            raise ValueError("p must be prime")
        self.p = p

    def add_table(self):
        r = np.arange(self.p)
        return (r[:, None] + r[None, :]) % self.p

    def mul_table(self):
        r = np.arange(self.p)
        return (r[:, None] * r[None, :]) % self.p

    def inv(self, a: int) -> int:
        return pow(a, -1, self.p)

    def primitive_elements(self) -> list[int]:
        return [g for g in range(1, self.p)
                if len({pow(g, k, self.p) for k in range(1, self.p)}) == self.p - 1]
